# ---------- README blocks ----------

def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def data_block():
    (a0, a1), (b0, b1) = STATS["periods"]
    ma, mb = STATS["matches"]
    parts = [f"Source: MySquadStats API, vanilla servers. Window A: {a0} to {a1} ({ma:,} matches). "
             f"Window B: {b0} to {b1} ({mb:,} matches). The API allows 92 days per request.", ""]
    gm = STATS["gamemodes"]
    ta, tb = sum(x[1] for x in gm), sum(x[2] for x in gm)
    parts += ["**Game modes**", "", table(["Mode", "Matches A", "Matches B", "Share B"],
              [(m, f"{a:,}", f"{b:,}", f"{b / tb * 100:.1f}%") for m, a, b in gm]), ""]
    parts += ["**Maps** (share of matches on the 23 vanilla maps, change = share B against share A)", "",
              table(["#", "Map", "Matches B", "Share B", "Change", "Size", "Biome"],
                    [(i + 1, m, f"{model.MAP_B[m]:,}", f"{SHARE[m]:.1f}%", f"{trend(m):+.0f}%",
                      f"{model.KM[m]} km ({size_class(m)})", BIOME[m].title()) for i, m in enumerate(MAPS)]), ""]
    rows = []
    for m in MAPS:
        raas = sorted((x for x in LAYERS if LAYERS[x]["map"] == m and LAYERS[x]["mode"] == "RAAS"),
                      key=lambda x: -LAYER_B.get(x, 0))
        inv = best(m, "Invasion")
        allinv = [x for x in LAYERS if LAYERS[x]["map"] == m and LAYERS[x]["mode"] == "Invasion"]
        rows.append((m, ", ".join(f"{x.split('_', 1)[1].replace('_', ' ')} ({LAYER_B.get(x, 0):,})" for x in raas),
                     ", ".join(f"{x.split('_', 1)[1].replace('_', ' ')} ({LAYER_B.get(x, 0):,})"
                               for x in sorted(allinv, key=lambda x: -LAYER_B.get(x, 0))) or "none",
                     inv.split("_", 1)[1].replace("_", " ") if inv else "-"))
    parts += ["**Layer versions per map** (matches in window B, most played first)", "",
              table(["Map", "RAAS", "Invasion", "Best Invasion"], rows), ""]
    up = [m for m in sorted(MAPS, key=trend, reverse=True) if trend(m) > 3]
    down = [m for m in sorted(MAPS, key=trend) if trend(m) < -3]
    parts += [f"**Rising:** {', '.join(f'{m} ({trend(m):+.0f}%)' for m in up)}.  ",
              f"**Falling:** {', '.join(f'{m} ({trend(m):+.0f}%)' for m in down)}."]
    return "\n".join(parts)


def pools_block(pools, res):
    real3 = sum(model.MAP_B[m] for m in TOP3) / sum(model.MAP_B.values()) * 100
    real5 = sum(model.MAP_B[m] for m in TOP5) / sum(model.MAP_B.values()) * 100
    t = res["00-today"]
    head = ["Pool", "Layers", "Vote", "Big 3 share", "Big 3 next round", "Big 3 in 3 rounds",
            "Maps / day", "Maps / week", "RAAS", "Rules relaxed"]
    rows = []
    for p in pools:
        r, s = res[p.key], p.settings
        n = sorted({len(layers) for layers, _ in p.files.values()})
        rows.append((f"[{p.title}](src/configs/pools/{p.key})", f"{n[0]}-{n[-1]}" if len(n) > 1 else n[0],
                     f"{s.raas}R+{s.invasion}I, skip {s.map_skip}" + (", biome" if s.biome_skip else ""),
                     f"{r['top3']:.0f}%", f"{r['top3_next']:.0f}%", f"{r['top3_in3']:.0f}%",
                     f"{r['maps_day']:.1f}", f"{r['maps_week']:.1f}", f"{r['raas']:.0f}%", f"{r['relaxed']:.0f}%"))
    check = (f"Check of the model: the \"today\" pool gives a big 3 share of {t['top3']:.0f}% and a top 5 share of "
             f"{t['top5']:.0f}%. Real servers in window B: {real3:.0f}% and {real5:.0f}% "
             f"(of the 23 maps).")
    desc = [f"- **{p.title}** (`{p.key}`): {p.note}" for p in pools if not p.key[3:].startswith("cycle")]
    return "\n".join([check, "", table(head, rows), "", *desc])


def replace_block(text, name, body):
    pat = re.compile(rf"(<!-- BEGIN:{name} -->\n).*?(<!-- END:{name} -->)", re.S)
    if not pat.search(text):
        raise SystemExit(f"README marker {name} missing")
    return pat.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)


def main():
    pools = build()
    for p in pools:
        for layers, _ in p.files.values():
            bad = [x for x in layers if x not in LAYERS]
            if bad:
                raise SystemExit(f"{p.key}: unknown layers {bad}")
    write_cfgs(pools)
    with Workers() as w:
        res = dict(w.map(run, pools))
    with open(os.path.join(ROOT, "src", "configs", "results.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump({k: {a: (round(b, 2) if isinstance(b, float) else b) for a, b in v.items()}
                   for k, v in res.items()}, f, indent=1)
    charts(pools, res)
    if os.path.exists(README):
        with open(README, encoding="utf-8") as f:
            text = f.read()
        text = replace_block(text, "data", data_block())
        text = replace_block(text, "pools", pools_block(pools, res))
        with open(README, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    for p in pools:
        r = res[p.key]
        print(f"{p.key:28} top3 {r['top3']:5.1f}  in3 {r['top3_in3']:5.1f}  day {r['maps_day']:4.1f}  "
              f"week {r['maps_week']:4.1f}  raas {r['raas']:5.1f}  relax {r['relaxed']:5.1f}  empty {r['empty']:.2f}")


if __name__ == "__main__":
    main()
