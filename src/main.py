README = os.path.join(ROOT, "README.md")


# ---------- cfg files ----------

def vote_lines(p):
    s = p.settings
    modes = [f"RAAS {s.raas}"] if s.raas else []
    modes += [f"Invasion {s.invasion}"] if s.invasion else []
    out = [
        "// Merge these keys into ServerConfig/VoteConfig.cfg. Keys not listed here stay as they are.",
        "// Needs Server.cfg: MapRotationMode=LayerList_Vote and UseVoteLayer=true",
        f"LayerOptionsNumber={s.options}",
        f"GameModeChoices={', '.join(modes)}",
        f"CanRegenerateLayerList={'true' if s.reroll else 'false'}",
        f"MapSkipRounds={s.map_skip}",
        f"MapBiomeSkipRounds={s.biome_skip}",
        "LayerSizeSkipRounds=0",
        f"UniqueMap={'true' if s.unique else 'false'}",
    ]
    for k, v in p.extra_vote.items():
        out += ["// Evening window in server time. Example value, set it to your own busy hours.",
                f"{k}={v}"]
    return out


def write_cfgs(pools):
    if os.path.isdir(POOL_DIR):
        shutil.rmtree(POOL_DIR)
    for p in pools:
        d = os.path.join(POOL_DIR, p.key)
        for rel, (layers, label) in p.files.items():
            path = os.path.join(d, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            raas = sum(LAYERS[x]["mode"] == "RAAS" for x in layers)
            head = [f"// {p.title}: {label}", f"// {len(layers)} layers: {raas} RAAS, {len(layers) - raas} Invasion",
                    "// One Layer_Id per line. Generated by src/main.py."]
            if rel.startswith("week-"):
                head.append("// Copy to ServerConfig/LayerVoting.cfg at the weekly restart.")
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write("\n".join(head + [""] + layers) + "\n")
        with open(os.path.join(d, "VoteConfig.cfg"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(vote_lines(p)) + "\n")


# ---------- simulation ----------

def run(p):
    hist, extra = model.simulate(p.schedule, p.settings)
    return p.key, model.metrics(hist, extra)


